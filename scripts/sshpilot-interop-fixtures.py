#!/usr/bin/env python3
"""Generate synthetic interoperability fixtures and verify Haven's portable export.

Run with SSHPilot's test Python, passing its source tree and either `generate` or
`verify`. No user config, keyring, PAM, or real server is accessed.
"""
import base64
import pathlib
import sys
import types


ROOT = pathlib.Path(__file__).resolve().parent.parent
SSHPILOT = pathlib.Path(sys.argv[1]).resolve()
PACKAGE = types.ModuleType("sshpilot")
PACKAGE.__path__ = [str(SSHPILOT / "src/sshpilot")]
sys.modules["sshpilot"] = PACKAGE
from sshpilot.backup_archive import write_spbk
from sshpilot.special_backup import read_special_yaml, write_special_yaml


def generate():
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ed25519, rsa

    dest = ROOT / "core/ssh/src/test/resources/sshpilot"
    dest.mkdir(parents=True, exist_ok=True)
    plain = ed25519.Ed25519PrivateKey.generate()
    encrypted = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    no_passphrase = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    keys = []
    for name, key, password in (("id_plain", plain, None),
                                ("id_encrypted", encrypted, "密钥口令🔑"),
                                ("id_locked", no_passphrase, "separate-key-password")):
        private = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH,
                                    serialization.BestAvailableEncryption(password.encode())
                                    if password else serialization.NoEncryption())
        public = key.public_key().public_bytes(serialization.Encoding.OpenSSH,
                                               serialization.PublicFormat.OpenSSH)
        keys.append({"path": f"/home/fixture/.ssh/{name}", "mode": 0o600,
                     "content_b64": base64.b64encode(private).decode(),
                     "public_path": f"/home/fixture/.ssh/{name}.pub", "public_mode": 0o644,
                     "public_content_b64": base64.b64encode(public).decode()})
    config = '''Host jump
    HostName bastion.example.test
    User deploy
    IdentityFile /home/fixture/.ssh/id_plain
Host web
    HostName web.example.test
    User 测试
    Port 2222
    ProxyJump jump
    IdentityFile /home/fixture/.ssh/id_encrypted
    ForwardAgent yes
Host locked
    HostName locked.example.test
    User root
    IdentityFile /home/fixture/.ssh/id_locked
'''
    manifest = {"version": 1, "format": "sshpilot-cn-special-backup", "fork_only": True,
                "source_home": "/home/fixture", "app_config": {"ui": {"theme": "dark"}},
                "ssh_config": "Include conf.d/*.conf\nHost *\n    ServerAliveInterval 30\n",
                "ssh_config_files": {"config": "Include conf.d/*.conf\nHost *\n    ServerAliveInterval 30\n",
                                     "conf.d/servers.conf": config},
                "ssh_config_root": "/home/fixture/.ssh", "ssh_config_main_rel": "config",
                "known_hosts": "web.example.test ssh-ed25519 AAAA\n",
                "credentials": [{"id": "测试@web.example.test", "type": "password",
                                 "host": "web.example.test", "username": "测试", "secret": "服务器密码🔐"},
                                {"id": "/home/fixture/.ssh/id_encrypted", "type": "key",
                                 "secret": "密钥口令🔑", "metadata": {"key_path": "/home/fixture/.ssh/id_encrypted"}}],
                "private_keys": keys,
                "connection_store": {"version": 1,
                    "connections": [{"id": name, "nickname": name, "protocol": "ssh", "display_name": label}
                                    for name, label in (("jump", "跳板"), ("web", "生产服务器"), ("locked", "加密密钥"))],
                    "groups": [{"id": "prod", "name": "生产", "parent_id": None, "order": 0, "connection_ids": ["jump"]},
                               {"id": "servers", "name": "服务器", "parent_id": "prod", "order": 1, "connection_ids": ["web", "locked"]}],
                    "root_connection_ids": [], "metadata": []}}
    password = "备份密码🔒-not-a-real-password"
    write_special_yaml(str(dest / "python-special.yaml"), manifest, password)
    write_spbk(str(dest / "python-encrypted.spbk"), manifest, password)
    write_spbk(str(dest / "python-plain.spbk"), manifest)
    (dest / "README.md").write_text(
        "Synthetic test servers and randomly generated throwaway keys. Never use these keys.\n"
        "Generated by scripts/sshpilot-interop-fixtures.py from SSHPilot CN's real writers.\n"
        "Backup password: `备份密码🔒-not-a-real-password`\n", encoding="utf-8")
    print(f"Generated 3 encrypted/plain fixtures in {dest}")


def verify():
    import tempfile
    import paramiko

    output = ROOT / "core/ssh/build/sshpilot-interop/haven-special.yaml"
    manifest = read_special_yaml(str(output), "安卓导出🔒")
    expected = {"生产服务器", "跳板", "加密密钥"}
    entries = manifest["connection_store"]["connections"]
    assert {c["display_name"] for c in entries} == expected
    assert len(manifest["private_keys"]) == 3
    config = paramiko.SSHConfig.from_text(manifest["ssh_config"])
    web = next(c for c in entries if c["display_name"] == "生产服务器")
    jump = next(c for c in entries if c["display_name"] == "跳板")
    lookup = config.lookup(web["id"])
    assert lookup["hostname"] == "web.example.test"
    assert lookup["port"] == "2222"
    assert lookup["user"] == "测试"
    assert lookup["proxyjump"] == jump["id"]
    assert any(c["secret"] == "服务器密码🔐" for c in manifest["credentials"])
    encrypted = [k for k in manifest["private_keys"] if b"OPENSSH PRIVATE KEY" in base64.b64decode(k["content_b64"])]
    assert len(encrypted) == 3
    from sshpilot.backup_manager import BackupManager, _rebase_home_path
    from sshpilot.special_backup import FULL_BACKUP_OPTIONS
    from cryptography.hazmat.primitives.serialization import load_ssh_private_key
    config_stub = types.SimpleNamespace(get_setting=lambda key, default=None: default)
    manager = BackupManager.__new__(BackupManager)
    manager.config = config_stub
    valid, reason = manager._validate_import_data(manifest)
    assert valid, reason
    assert manager._restore_options_for_manifest(manifest, FULL_BACKUP_OPTIONS)["app_settings"]
    # Exercise the desktop's actual key writer with a temporary destination home.
    import sshpilot.backup_manager as bm
    import sshpilot.secret_storage as secret_storage
    from sshpilot.core.connections.repository import ConnectionRepository
    from sshpilot.core.connections.ssh_config_store import SshConfigStore
    from sshpilot.secret_storage import passphrase_spec
    from unittest.mock import patch
    with tempfile.TemporaryDirectory(prefix="haven-sshpilot-test-") as home:
        manager.last_merge_dropped_globals = 0
        manager.last_merge_partial_collisions = []
        root = pathlib.Path(home) / "ssh_config"
        root.write_text("", encoding="utf-8")
        manager._merge_ssh_config_fragment(str(root), [bm._rebase_home_in_text(
            manifest["ssh_config"], manifest["source_home"], home)])
        repository = ConnectionRepository(ssh_store=SshConfigStore(root),
            state_path=pathlib.Path(home) / "connections.json",
            legacy_config_path=pathlib.Path(home) / "config.json", isolated=False)
        restored = repository.restore_connection_store(manifest["connection_store"], mode="merge")
        assert not restored.warnings
        snapshot = repository.snapshot()
        assert {c.display_name for c in snapshot.connections} == expected
        assert {g.name for g in snapshot.groups} == {"生产", "生产 / 服务器"}
        assert sum(len(g.connection_ids) for g in snapshot.groups) == 3
        class Secrets:
            def __init__(self):
                self.values = {}
            def persists_secrets(self):
                return True
            def lookup_everywhere(self, spec):
                return None
            def store(self, spec, value):
                self.values[spec.keyring_account] = value
                return True
        secrets = Secrets()
        with patch.object(bm, "_current_home", return_value=home):
            with patch.object(secret_storage, "get_secret_manager", return_value=secrets):
                assert manager._restore_credentials(manifest) == 2
            written, skipped = manager._restore_private_keys(manifest)
            assert (written, skipped) == (3, 0)
            passphrases = {c["metadata"]["key_path"]: c["secret"] for c in manifest["credentials"] if c["type"] == "key"}
            for item in manifest["private_keys"]:
                path = pathlib.Path(_rebase_home_path(item["path"], manifest["source_home"], home))
                assert path.is_file()
                assert path.stat().st_mode & 0o777 == 0o600
                password = passphrases.get(item["path"])
                if password:
                    load_ssh_private_key(path.read_bytes(), password.encode())
                    # Credentials must be filed under the SAME re-homed key path.
                    assert str(path) == _rebase_home_path(item["path"], manifest["source_home"], home)
                    assert secrets.values[passphrase_spec(str(path)).keyring_account] == password
    print("Python verified Haven export: AES-GCM/scrypt, 3 servers, names, groups, ProxyJump, credentials, encrypted keys and desktop key restore.")


if __name__ == "__main__":
    {"generate": generate, "verify": verify}[sys.argv[2]]()
